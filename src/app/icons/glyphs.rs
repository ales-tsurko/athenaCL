//! Canonical UI icon artwork. Add an enum variant and its square pixel mask here.
//! Each character is one square pixel: `#` is ink, `.` is transparent.

/// A monochrome icon with a native pixel grid.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Icon {
    /// Metronome.
    Metronome,
    /// Closed folder.
    Folder,
    /// Open folder, with its front folded forward.
    FolderOpen,
    /// Outlined circle.
    CircleOutline,
    /// Filled circle.
    CircleFilled,
    /// Play.
    Play,
    /// Pause.
    Pause,
    /// Speaker with sound waves.
    Speaker,
    /// Speaker with a mute mark.
    Muted,
    /// Paired notes for the MIDI sound font.
    SoundFont,
    /// Chevron up.
    ChevronUp,
    /// Chevron down.
    ChevronDown,
}

